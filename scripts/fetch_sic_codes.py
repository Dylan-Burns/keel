"""Regenerate `config/sic_codes.yaml` from the SEC SIC code list page.

The company browser of the admin companies page groups the industries of
the SEC by the office of the Division of Corporation Finance that reviews
their filings. This script fetches the SEC page once, through
`keel.edgar.EdgarClient` (the same User-Agent, rate limit, and allow list
as production), reads its table (SIC code, office, industry title), and
writes the YAML file with the fetch date. The service never fetches the
page: it reads the committed file.

Run from the repository root:

    uv run python scripts/fetch_sic_codes.py
"""

from __future__ import annotations

import argparse
import datetime
import html
import html.parser
import json
import pathlib
import tempfile

from keel import config
from keel import edgar

SIC_LIST_URL = (
    "https://www.sec.gov/search-filings/"
    "standard-industrial-classification-sic-code-list"
)
DEFAULT_OUT = pathlib.Path("config/sic_codes.yaml")
HEADER = """\
# The SEC industries (SIC codes) and the office that reviews their filings.
# Generated by scripts/fetch_sic_codes.py from the SEC SIC code list page;
# do not edit by hand. The company browser of the admin companies page
# shows each office as a sector and each code as an industry.
"""


class _TableParser(html.parser.HTMLParser):
    """Collect the text of every table cell, row by row."""

    def __init__(self) -> None:
        super().__init__()
        self.rows: list[list[str]] = []
        self._row: list[str] | None = None
        self._cell: list[str] | None = None

    def handle_starttag(
        self, tag: str, attrs: list[tuple[str, str | None]]
    ) -> None:
        del attrs
        if tag == "tr":
            self._row = []
        elif tag in {"td", "th"} and self._row is not None:
            self._cell = []

    def handle_endtag(self, tag: str) -> None:
        if tag in {"td", "th"} and self._row is not None:
            if self._cell is not None:
                self._row.append(" ".join("".join(self._cell).split()))
            self._cell = None
        elif tag == "tr" and self._row is not None:
            self.rows.append(self._row)
            self._row = None

    def handle_data(self, data: str) -> None:
        if self._cell is not None:
            self._cell.append(html.unescape(data))


def parse_sic_table(page: str) -> list[dict[str, str]]:
    """Read the SIC rows of the SEC page.

    Args:
        page: The HTML of the page.

    Returns:
        1 mapping per industry with `code` (4 digits), `office`, and
        `title`, in code order.

    Raises:
        ValueError: The page has no SIC table.
    """
    parser = _TableParser()
    parser.feed(page)
    rows = []
    for row in parser.rows:
        if len(row) != 3 or not row[0].isdigit():
            continue
        code, office, title = row
        rows.append({"code": code.zfill(4), "office": office, "title": title})
    if not rows:
        raise ValueError(f"no SIC table in {SIC_LIST_URL}")
    return sorted(rows, key=lambda r: r["code"])


def render(industries: list[dict[str, str]]) -> str:
    """Write the YAML text: 1 flow mapping per industry, every value quoted.

    Args:
        industries: The rows of `parse_sic_table`.

    Returns:
        The file text.
    """
    lines = [
        HEADER.rstrip("\n"),
        f"source: {json.dumps(SIC_LIST_URL)}",
        f"fetched: {json.dumps(datetime.date.today().isoformat())}",
        "industries:",
    ]
    for row in industries:
        code, office, title = (
            json.dumps(row[key]) for key in ("code", "office", "title")
        )
        lines.append(f"  - {{code: {code}, office: {office}, title: {title}}}")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Fetch the page, parse it, and write the YAML file.

    Returns:
        The process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    settings = config.load_settings()
    with tempfile.TemporaryDirectory() as scratch:
        client = edgar.EdgarClient(
            settings.edgar.user_agent,
            pathlib.Path(scratch),
            min_interval=settings.edgar.min_request_interval_seconds,
        )
        with client:
            body = client.fetch(SIC_LIST_URL)
    industries = parse_sic_table(body.decode("utf-8", errors="replace"))
    args.out.write_text(render(industries), encoding="utf-8")
    print(f"{len(industries)} industries; wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
